/**
 * Copies the API's route types into this package, so the published client needs nothing from the server.
 *
 * Emits declarations for apps/api and takes `src/routes/api.d.ts`: the type of the route tree, which references
 * only `hono`. Written as a `.ts` file of declarations (not `.d.ts`) so `tsc` carries it into `dist`.
 * Run with `pnpm --filter @moonthug/p0s-client generate` after changing any route. CI fails if it's stale.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const root = join(import.meta.dirname, '../../..');
const out = mkdtempSync(join(tmpdir(), 'p0s-routes-'));

try {
  execFileSync(
    join(root, 'node_modules/.bin/tsc'),
    [
      ...['-p', 'apps/api', '--noEmit', 'false', '--declaration', '--emitDeclarationOnly', '--outDir', out],
      // TypeScript 7 checks in parallel, so the order of union members depends on the machine's core count, and the
      // output would differ between a laptop and CI. Stable ordering alone still varied at high checker counts;
      // single-threaded is the same everywhere, and this file is small enough that speed doesn't matter.
      '--stableTypeOrdering',
      '--singleThreaded',
    ],
    { cwd: root, stdio: 'inherit' },
  );

  const declarations = readFileSync(join(out, 'src/routes/api.d.ts'), 'utf8');
  const header = '// Generated by scripts/generateRoutes.mjs from apps/api/src/routes/api.ts. Do not edit.\n\n';

  writeFileSync(join(import.meta.dirname, '../src/generated/routes.ts'), header + declarations);
  console.log('wrote src/generated/routes.ts');
} finally {
  rmSync(out, { recursive: true, force: true });
}
